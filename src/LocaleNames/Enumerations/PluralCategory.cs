namespace LocaleNames.Enumerations
{
    /// <summary>
    /// Provides CLDR plural categories used for count dependent names (e.g. currency names).
    /// </summary>
    public enum PluralCategory
    {
        /// <summary>
        /// The zero plural category.
        /// </summary>
        Zero = 0,

        /// <summary>
        /// The one plural category.
        /// </summary>
        One = 1,

        /// <summary>
        /// The two plural category.
        /// </summary>
        Two = 2,

        /// <summary>
        /// The few plural category.
        /// </summary>
        Few = 3,

        /// <summary>
        /// The many plural category.
        /// </summary>
        Many = 4,

        /// <summary>
        /// The other plural category.
        /// </summary>
        Other = 5
    }
}
